async function run() {
  console.log(`Strapi: ${getStrapiBaseUrl()}`);
  console.log(`Products: ${DESCRIPTIONS.length}${DRY_RUN ? '  (DRY RUN)' : ''}\n`);

  let updated = 0, notFound = 0, failed = 0;

  for (const { title, description } of DESCRIPTIONS) {
    if (DRY_RUN) {
      console.log(`[preview]  ${title}`);
      console.log(description.slice(0, 80) + '…\n');
      continue;
    }

    const product = await findProduct(title);
    if (!product) {
      console.log(`[not found]    ${title}`);
      notFound++;
      continue;
    }

    try {
      await updateDescription(product.documentId, description);
      console.log(`[updated]      ${title}`);
      updated++;
    } catch (err) {
      console.log(`[failed]       ${title}: ${err.message}`);
      failed++;
    }
  }

  if (!DRY_RUN) {
    console.log(`\nDone.  Updated: ${updated}  Not found: ${notFound}  Failed: ${failed}`);
  }
}

run().catch((err) => {
  console.error('Fatal:', err.message);
  process.exit(1);
});
