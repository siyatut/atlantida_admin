async function main() {
  const base = getStrapiBaseUrl();
  console.log(`Strapi: ${base}`);
  console.log(`Descriptions to upload: ${DESCRIPTIONS.length}`);
  if (DRY_RUN) console.log('DRY RUN — no changes will be made\n');
  else console.log();

  let updated = 0;
  let failed = 0;

  for (const { title, description } of DESCRIPTIONS) {
    const product = await findProduct(title);
    if (!product) {
      console.error(`  [not found] "${title}"`);
      failed++;
      continue;
    }
    if (DRY_RUN) {
      console.log(`  [dry-run]  "${title}" → ${product.documentId}`);
      updated++;
      continue;
    }
    try {
      await updateDescription(product.documentId, description);
      console.log(`  [updated]  "${title}"`);
      updated++;
    } catch (err) {
      console.error(`  [error]    "${title}": ${err.message}`);
      failed++;
    }
  }

  console.log(`\nDone.  Updated: ${updated}  Failed: ${failed}`);
}

main().catch((err) => {
  console.error(err.message);
  process.exit(1);
});
